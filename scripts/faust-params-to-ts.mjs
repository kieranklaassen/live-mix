// Emits the TypeScript parameter table for one Faust device from the compiler's
// JSON description (`faust -json`). Run by scripts/build-faust.sh; the output
// is committed next to the hand-written device tables and re-derived in CI.
//
// Ids are the depth-first order of the active widgets in the UI tree, which is
// the order the generated buildUserInterface() declares them and therefore the
// order cpp/faust/common/faust_runtime.h numbers them for device_set_param.

import { readFileSync } from 'node:fs'

const [jsonPath, deviceName] = process.argv.slice(2)
if (!jsonPath || !deviceName) {
  console.error('usage: node scripts/faust-params-to-ts.mjs <faust.json> <device-name>')
  process.exit(2)
}

const ACTIVE_WIDGETS = new Set(['hslider', 'vslider', 'nentry', 'button', 'checkbox'])

function* activeWidgets(items) {
  for (const item of items) {
    if (Array.isArray(item.items)) yield* activeWidgets(item.items)
    else if (ACTIVE_WIDGETS.has(item.type)) yield item
  }
}

const words = (text) => text.split(/[^A-Za-z0-9]+/).filter(Boolean)
const capitalise = (word) => word[0].toUpperCase() + word.slice(1).toLowerCase()
const camelCase = (text) =>
  words(text)
    .map((word, index) => (index === 0 ? word.toLowerCase() : capitalise(word)))
    .join('')
const pascalCase = (text) => words(text).map(capitalise).join('')
const quote = (text) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

const description = JSON.parse(readFileSync(jsonPath, 'utf8'))
const params = [...activeWidgets(description.ui)].map((widget, id) => {
  const meta = Object.assign({}, ...(widget.meta ?? []))
  const scale = meta.scale ?? 'lin'
  if (scale !== 'lin' && scale !== 'log') {
    throw new Error(`${widget.label}: [scale:${scale}] has no ParamTaper equivalent`)
  }
  const key = camelCase(widget.label)
  if (!/^[a-z][A-Za-z0-9]*$/.test(key)) {
    throw new Error(`${widget.label}: label does not camel-case to an identifier`)
  }
  return {
    key,
    id,
    name: widget.label,
    min: widget.min ?? 0,
    max: widget.max ?? 1,
    default: widget.init ?? 0,
    taper: scale === 'log' ? 'log' : 'linear',
    unit: meta.unit ?? '',
  }
})

const keys = new Set(params.map((param) => param.key))
if (keys.size !== params.length) {
  throw new Error(`${deviceName}: two widgets camel-case to the same key`)
}

const constName = `${words(deviceName).join('_').toUpperCase()}_PARAMS`
const typeName = `${pascalCase(deviceName)}ParamName`

const lines = [
  `// GENERATED by scripts/build-faust.sh from cpp/faust/${deviceName}.dsp. Do not edit.`,
  '// Ids follow the Faust UI declaration order, the numbering',
  '// cpp/faust/common/faust_runtime.h uses for device_set_param.',
  '',
  "import { type ParamSpec } from '../../../core/params'",
  '',
  `export const ${constName} = {`,
]
for (const param of params) {
  lines.push(
    `  ${param.key}: {`,
    `    id: ${param.id},`,
    `    name: ${quote(param.name)},`,
    `    min: ${param.min},`,
    `    max: ${param.max},`,
    `    default: ${param.default},`,
    `    taper: ${quote(param.taper)},`,
    `    unit: ${quote(param.unit)},`,
    '  },',
  )
}
lines.push(
  '} as const satisfies Record<string, ParamSpec>',
  '',
  `export type ${typeName} = keyof typeof ${constName}`,
  '',
)

process.stdout.write(lines.join('\n'))
