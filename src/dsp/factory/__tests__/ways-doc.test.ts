// The table of ways as a page. docs/ways-generated.md is written from `WAYS`
// and checked against it here, so the page cannot say another thing than the
// code does. A way that is added, renamed or reworded is written to the page
// with:
//   UPDATE_WAYS_DOC=1 pnpm vitest run src/dsp/factory/__tests__/ways-doc.test.ts
// The page goes through prettier with the repository's own settings before it
// is written and before it is compared, because `pnpm lint` checks docs/ and
// prettier pads a table.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import prettier from 'prettier'
import { describe, expect, it } from 'vitest'

import { WAYS, WAY_FAMILIES } from '..'

const file = join(dirname(fileURLToPath(import.meta.url)), '../../../../docs/ways-generated.md')

const cell = (text: string): string => text.replaceAll('|', '\\|')

async function page(): Promise<string> {
  const lines = [
    '# Ways of playing',
    '',
    '<!-- GENERATED by src/dsp/factory/__tests__/ways-doc.test.ts from the table in src/dsp/factory/ways. Do not edit. -->',
    '',
    'The ways a sound can be played (`WAYS`), family by family in the order a',
    'host lists them. What a way is, what a take keeps and how takes are counted',
    'is in [factory.md](./factory.md#a-way-of-playing-a-sound). The last column',
    'is where `far` stands when a host names none.',
  ]
  for (const family of WAY_FAMILIES) {
    lines.push(
      '',
      `## ${family.name}`,
      '',
      '| Way id | Name | What it needs | What it does | What `far` changes | `far` |',
      '| --- | --- | --- | --- | --- | --- |',
    )
    for (const way of WAYS.filter((each) => each.family === family.id)) {
      lines.push(
        `| \`${way.id}\` | ${cell(way.name)} | ${cell(way.needs)} | ${cell(way.words)} | ${cell(way.far.words)} | ${way.far.default} |`,
      )
    }
  }
  const options = await prettier.resolveConfig(file)
  return prettier.format(`${lines.join('\n')}\n`, { ...options, filepath: file })
}

describe('the page of ways', () => {
  it('lists twenty ways in six families', () => {
    expect(WAYS).toHaveLength(20)
    expect(WAY_FAMILIES).toHaveLength(6)
    for (const family of WAY_FAMILIES) {
      expect(
        WAYS.some((way) => way.family === family.id),
        family.id,
      ).toBe(true)
    }
  })

  it('says what the table says', async () => {
    const written = await page()
    if (process.env.UPDATE_WAYS_DOC) writeFileSync(file, written)
    expect(
      existsSync(file) ? readFileSync(file, 'utf8') : '',
      'write it with UPDATE_WAYS_DOC=1',
    ).toBe(written)
  })
})
